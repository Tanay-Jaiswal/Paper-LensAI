"""Reviewer mode: a short peer-review draft (summary, strengths, weaknesses, questions for the authors).

Every point is one finding PaperLens already made (an evidence-ledger rating, a checklist item, an evidence gap, a
Numbers check, a reference check), written out with fixed wording for its kind and cited to a page. Nothing is
generated by a language model and nothing new is judged here, so the same paper always gets the same review, and each
point names the finding it came from so a reader can check it.

What it is not: a verdict on novelty, correctness, significance or whether the paper should be accepted. Those need a
human reviewer who has read the paper; the review says so at the end.
"""
from __future__ import annotations

import html

from . import __version__
from .pipeline import NOT_ASSESSED, Analysis
from .scorecard import build_scorecard

MAX_STRENGTHS, MAX_WEAKNESSES, MAX_QUESTIONS = 5, 6, 6
# gap kinds the reproducibility checklist already reports item by item (as in revisions.py): listed once, not twice
_COVERED_BY_RUBRIC = {"no_code", "no_hyperparameters", "no_limitations", "no_splits", "code_promised_not_linked"}
_SEV = {"high": 0, "medium": 1, "low": 2}

# a question to the authors for each kind of weakness ({page} and {claim} are filled in)
_GAP_QUESTION = {
    "unsupported_claim": "Which result in the paper supports the claim \"{claim}\" ({page})?",
    "number_not_in_results": "Where in the results do the figures in \"{claim}\" ({page}) come from?",
    "significance_without_test": "Which statistical test supports calling the result significant ({page}), and what "
                                 "is the p-value or confidence interval?",
    "improvement_without_variance": "How much do the results vary over runs or seeds, and is the gain ({page}) larger "
                                    "than that variation?",
    "superlative_without_baselines": "Which baselines support the superlative wording ({page})?",
    "superlative_unsupported": "Which head-to-head comparison supports the superlative wording ({page})?",
    "comparison_without_baselines": "What exactly are the comparisons made against ({page})?",
    "generalization_narrow_evidence": "Does the general claim ({page}) hold beyond the datasets tested?",
    "test_set_tuning": "Were hyperparameters or checkpoints chosen on the test set ({page})? If so, can the test results "
                       "be reported with choices made on a validation set?",
    "baseline_numbers_copied": "Do the copied baseline numbers ({page}) use the same dataset version, split and metric "
                               "as your own experiments?",
    "small_gain_without_test": "Is the small gain ({page}) larger than the spread over random seeds?",
    "sota_single_run": "How many runs is the state-of-the-art result ({page}) based on, and what is their spread?",
    "code_promised_not_linked": "Where can the code be obtained ({page})?",
}
_GAP_WEAKNESS = {
    "unsupported_claim": "The claim \"{claim}\" ({page}) has no supporting passage in the results, tables or discussion.",
    "number_not_in_results": "Figures stated in \"{claim}\" ({page}) do not appear in the results text or tables.",
}


def _short(text: str, n: int = 110) -> str:
    text = " ".join(text.split())
    return text if len(text) <= n else text[:n].rsplit(" ", 1)[0] + " ..."


def _page(p) -> str:
    return f"p.{p}" if p else "no page"


def _point(text: str, page, source: str, quote: str = "", key: str = "", severity: str = "") -> dict:
    return {"text": text, "page": page, "source": source, "quote": _short(quote, 300) if quote else "",
            "key": key, "severity": severity}


def _strengths(a: Analysis) -> list[dict]:
    out = []
    for c in a.claims:
        if c.support == "strong" and c.evidence:
            e = c.evidence[0]
            out.append(_point(f"The claim \"{_short(c.text)}\" ({_page(c.page)}) is backed by a passage that repeats its "
                              f"figures ({_page(e.page)}).", e.page, f"Evidence ledger, claim {c.id} (strong)", e.quote,
                              f"claim:{c.id}"))
    items = sorted((i for i in a.rubric.get("items", []) if i["status"] == "present" and i["evidence"]),
                   key=lambda i: -i["weight"])
    for i in items:
        ev = i["evidence"][0]
        out.append(_point(f"{i['label']}: reported ({_page(ev['page'])}).", ev["page"],
                          f"Reproducibility item '{i['key']}' (weight {i['weight']})", ev["quote"], f"repro:{i['key']}"))
    cons = (a.consistency or {})
    if cons.get("n_consistent"):
        ok = [x for x in cons["checks"] if x["status"] == "consistent"]
        out.append(_point(f"{cons['n_consistent']} of {cons['n_checked']} statements whose arithmetic could be redone "
                          f"check out (for example {_page(ok[0]['page'])}).", ok[0]["page"],
                          f"Numbers check {ok[0]['id']}", ok[0]["quote"], f"number:{ok[0]['id']}"))
    cit = a.citations or {}
    if cit.get("checked") and not any(f["kind"] in ("cited_not_listed", "listed_not_cited") for f in cit["findings"]):
        out.append(_point(f"Every in-text citation matches an entry in the reference list ({cit['n_entries']} entries "
                          "checked).", None, "Reference checks"))
    # the strongest of each kind first: a claim, then checklist items, then the rest
    head = [p for p in out if p["key"].startswith("claim:")][:2]
    rest = [p for p in out if p not in head]
    return (head + rest)[:MAX_STRENGTHS]


def _weaknesses_and_questions(a: Analysis) -> tuple[list[dict], list[dict], list[dict]]:
    weak, minor, questions = [], [], []
    claim_by_id = {c.id: c for c in a.claims}
    for x in (a.consistency or {}).get("checks", []):
        if x["status"] == "inconsistent":
            weak.append(_point(f"The arithmetic on {_page(x['page'])} does not add up: {x['formula']}, but "
                               f"{x['stated']} is printed.", x["page"], f"Numbers check {x['id']}", x["quote"],
                               f"number:{x['id']}", x["severity"]))
            questions.append(_point(f"Which value is correct on {_page(x['page'])}: the printed {x['stated']}, or the "
                                    f"one implied by {x['formula']}?", x["page"], f"Numbers check {x['id']}",
                                    key=f"number:{x['id']}"))
    # gaps whose message names no claim (for example two superlatives without a comparison) are merged into one
    # point listing every page, so the review does not repeat itself
    groups: dict[tuple, list] = {}
    for g in a.gaps:
        if g.kind == "document_unreadable" or g.kind in _COVERED_BY_RUBRIC:
            continue
        c = claim_by_id.get(g.claim_id)
        key = (g.kind, g.claim_id) if g.kind in _GAP_WEAKNESS and c else (g.kind, g.message)
        groups.setdefault(key, []).append(g)
    for gs in groups.values():
        g = gs[0]
        c = claim_by_id.get(g.claim_id)
        pages = sorted({x.page for x in gs if x.page})
        where = ", ".join(_page(p) for p in pages) or "no page"
        fill = {"page": where, "claim": _short(c.text) if c else ""}
        if g.kind in _GAP_WEAKNESS and c:
            text = _GAP_WEAKNESS[g.kind].format(**fill)
        else:
            text = g.message.rstrip().rstrip(".") + (f" ({where})." if pages else ".")
        p = _point(text, g.page, "Evidence gap " + ", ".join(x.id for x in gs)
                   + (f", claim {g.claim_id}" if g.claim_id and len(gs) == 1 else ""), g.quote,
                   f"gap:{g.id}", min((x.severity for x in gs), key=lambda v: _SEV.get(v, 3)))
        (weak if p["severity"] in ("high", "medium") else minor).append(p)
        if g.kind in _GAP_QUESTION and (g.kind not in ("unsupported_claim", "number_not_in_results") or c):
            questions.append(_point(_GAP_QUESTION[g.kind].format(**fill), g.page, p["source"], key=f"gap:{g.id}",
                                    severity=p["severity"]))
    if a.rubric.get("band") != NOT_ASSESSED:
        for i in sorted(a.rubric.get("items", []), key=lambda i: -i["weight"]):
            if i["status"] != "missing":
                continue
            p = _point(f"{i['label']}: not found in the paper. {i['advice']}", None,
                       f"Reproducibility item '{i['key']}' (weight {i['weight']})", key=f"repro:{i['key']}",
                       severity="medium" if i["weight"] >= 2 else "low")
            (weak if i["weight"] >= 2 else minor).append(p)
            if i["weight"] >= 2:
                ask = i["advice"].rstrip(".")
                questions.append(_point(f"Can you {ask[0].lower() + ask[1:]}?", None, p["source"],
                                        key=p["key"], severity=p["severity"]))
    for f in (a.citations or {}).get("findings", []):
        p = _point(f["message"], f["page"], f"Reference check {f['id']}", f["quote"], f"reference:{f['id']}",
                   f["severity"])
        (weak if f["kind"] == "cited_not_listed" else minor).append(p)
    weak.sort(key=lambda p: _SEV.get(p["severity"], 3))
    questions.sort(key=lambda p: _SEV.get(p["severity"], 3))
    seen, uniq = set(), []
    for q in questions:           # one question per wording (several gaps of one kind ask the same thing)
        if q["text"] not in seen:
            seen.add(q["text"])
            uniq.append(q)
    return weak, minor, uniq


def build_review(a: Analysis) -> dict:
    card = build_scorecard(a)
    assessed = card["assessed"]
    tldr = (a.summary or {}).get("tldr", [])
    n_claims = len(a.claims)
    backed = sum(1 for c in a.claims if c.support in ("strong", "moderate"))
    summary = []
    if tldr:
        summary.append(f"In its own words, the paper says: \"{_short(tldr[0]['text'], 300)}\" ({_page(tldr[0]['page'])}).")
    if assessed:
        summary.append(f"PaperLens found {n_claims} headline claim{'s' if n_claims != 1 else ''}; {backed} "
                       f"{'is' if backed == 1 else 'are'} backed by a passage in the paper with matching wording or "
                       f"figures. The reporting checklist covers {a.rubric['score']} / 100 "
                       f"({(a.mode or {}).get('label', 'General')} checks), and the reporting grade is {card['grade']} "
                       f"({card['grade_text']}).")
    else:
        summary.append("Too little text could be extracted from this PDF (it may be scanned), so no review could be "
                       "drafted.")
    weak, minor, questions = _weaknesses_and_questions(a) if assessed else ([], [], [])
    return {
        "title": a.doc.title, "source_name": a.doc.source_name, "assessed": assessed,
        "summary": summary,
        "strengths": _strengths(a) if assessed else [],
        "weaknesses": weak[:MAX_WEAKNESSES],
        "questions": questions[:MAX_QUESTIONS],
        "minor": {"count": len(minor) + max(0, len(weak) - MAX_WEAKNESSES),
                  "note": "Further, lower-priority items are in the revision checklist and the References tab."},
        "grade": card["grade"],
        "method": "Rule-based: every point is an existing PaperLens finding written out with fixed wording. No language "
                  "model was used.",
        "limits": ("This draft covers how completely the paper reports its work and backs its claims with its own "
                   "results. It does not judge novelty, correctness of the method, significance, or whether the paper "
                   "should be accepted; a human reviewer has to read the paper for that. Check every point against the "
                   "cited page before using it."),
        "version": __version__,
    }


def _md_point(p: dict) -> str:
    return f"- {p['text']} *[{p['source']}]*"


def to_review_markdown(a: Analysis, r: dict | None = None) -> str:
    r = r or build_review(a)
    out = [f"# Review draft: {r['title']}", "", f"*{r['method']}*", "", "## Summary", ""] + r["summary"]
    if r["assessed"]:
        out += ["", "## Strengths", ""] + ([_md_point(p) for p in r["strengths"]] or ["- None found by the rules."])
        out += ["", "## Weaknesses", ""] + ([_md_point(p) for p in r["weaknesses"]] or ["- None found by the rules."])
        if r["minor"]["count"]:
            out.append(f"- Plus {r['minor']['count']} minor item(s). {r['minor']['note']}")
        out += ["", "## Questions for the authors", ""] + (
            [f"{i}. {q['text']}" for i, q in enumerate(r["questions"], 1)] or ["None."])
    out += ["", "## What this draft does not cover", "", r["limits"], "", f"*PaperLens {r['version']}*"]
    return "\n".join(out) + "\n"


_CSS = ("body{font:15px/1.6 Georgia,'Iowan Old Style',serif;max-width:820px;margin:2rem auto;padding:0 1rem;"
        "color:#1d1f1c}h1{font-size:22px}h2{font:600 13px system-ui,sans-serif;letter-spacing:.1em;text-transform:"
        "uppercase;color:#5c615a;border-top:1px solid #d8d0bf;padding-top:10px;margin-top:26px}.m{color:#5c615a;"
        "font:12.5px system-ui,sans-serif}li{margin-bottom:8px}q{color:#3b403b}")


def to_review_html(a: Analysis) -> str:
    r = build_review(a)
    e = html.escape

    def li(p):
        quote = f"<br><q>{e(p['quote'])}</q>" if p["quote"] else ""
        return f"<li>{e(p['text'])}{quote} <span class=m>[{e(p['source'])}]</span></li>"

    out = ["<!doctype html><html lang=en><meta charset=utf-8>", f"<title>Review draft: {e(r['title'])}</title>",
           f"<style>{_CSS}</style><body>", f"<h1>Review draft: {e(r['title'])}</h1>", f"<p class=m>{e(r['method'])}</p>",
           "<h2>Summary</h2>"] + [f"<p>{e(s)}</p>" for s in r["summary"]]
    if r["assessed"]:
        out += ["<h2>Strengths</h2><ul>"] + ([li(p) for p in r["strengths"]] or ["<li>None found by the rules.</li>"])
        out += ["</ul><h2>Weaknesses</h2><ul>"] + ([li(p) for p in r["weaknesses"]] or ["<li>None found by the rules.</li>"])
        if r["minor"]["count"]:
            out.append(f"<li class=m>Plus {r['minor']['count']} minor item(s). {e(r['minor']['note'])}</li>")
        out += ["</ul><h2>Questions for the authors</h2><ol>"] + (
            [f"<li>{e(q['text'])}</li>" for q in r["questions"]] or ["<li>None.</li>"]) + ["</ol>"]
    out += ["<h2>What this draft does not cover</h2>", f"<p>{e(r['limits'])}</p>",
            f"<p class=m>PaperLens {e(r['version'])}</p></body></html>"]
    return "\n".join(out)
