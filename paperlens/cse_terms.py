def lookup(abbr: str) -> tuple[str, str] | None:
    """Meaning and kind of `abbr`; exact case first, then a plural ("CNNs") or an all-capitals spelling ("RESNET")."""
    if abbr in CSE_TERMS:
        return CSE_TERMS[abbr]
    if abbr.endswith("s") and abbr[:-1] in CSE_TERMS:
        return CSE_TERMS[abbr[:-1]]
    for k, v in CSE_TERMS.items():
        if k.upper() == abbr and not k.isupper():
            return v
    return None
